import '../engine_utils.dart';
import '../i_engine.dart';

/// 播放列表中的一项。
class PlaylistTrack {
  final String path;
  final String title;
  final Duration duration;

  const PlaylistTrack({
    required this.path,
    this.title = '',
    this.duration = Duration.zero,
  });
}

/// 播放列表引擎：m3u / m3u8 / cue 互转。
class PlaylistEngine extends SimpleEngine {
  const PlaylistEngine();

  @override
  String get id => 'playlist';

  @override
  Future<void> execute(EngineContext context) async {
    final content = await readFileText(context.inputPath);
    final ext = inputExtension(context);
    final tracks = ext == 'cue' || content.trimLeft().startsWith('FILE ')
        ? _parseCue(content)
        : _parseM3u(content);
    if (tracks.isEmpty) {
      throw const EngineException('没有从输入文件里解析到播放条目');
    }
    final name = stringParam(context, 'name', inputStem(context));
    final target = context.targetFormat.toLowerCase();
    final text = switch (target) {
      'm3u' => _writeM3u(tracks, extended: true),
      'm3u8' => _writeM3u(tracks, extended: true, utf8Header: true),
      'cue' => _writeCue(tracks, name),
      _ => throw EngineException('播放列表引擎不支持输出格式：$target'),
    };
    await writeFileText(context.outputPath, text);
  }

  List<PlaylistTrack> _parseM3u(String content) {
    final tracks = <PlaylistTrack>[];
    var pendingTitle = '';
    var pendingDuration = Duration.zero;
    for (final rawLine in content.replaceAll('\r\n', '\n').split('\n')) {
      final line = rawLine.trim();
      if (line.isEmpty) continue;
      if (line.startsWith('#EXTINF:')) {
        final body = line.substring('#EXTINF:'.length);
        final commaIndex = body.indexOf(',');
        final secondsPart = commaIndex < 0 ? body : body.substring(0, commaIndex);
        pendingDuration = Duration(
          seconds: (double.tryParse(secondsPart.trim()) ?? 0).round(),
        );
        pendingTitle = commaIndex < 0 ? '' : body.substring(commaIndex + 1).trim();
        continue;
      }
      if (line.startsWith('#')) continue;
      tracks.add(PlaylistTrack(
        path: line,
        title: pendingTitle,
        duration: pendingDuration,
      ));
      pendingTitle = '';
      pendingDuration = Duration.zero;
    }
    return tracks;
  }

  List<PlaylistTrack> _parseCue(String content) {
    final tracks = <PlaylistTrack>[];
    String? currentFile;
    String pendingTitle = '';
    var pendingDuration = Duration.zero;
    for (final rawLine in content.replaceAll('\r\n', '\n').split('\n')) {
      final line = rawLine.trim();
      if (line.isEmpty) continue;
      final fileMatch = RegExp(r'^FILE\s+(.+?)\s+(\w+)$').firstMatch(line);
      if (fileMatch != null) {
        currentFile = _unquote(fileMatch.group(1)!);
        continue;
      }
      final titleMatch = RegExp(r'^TITLE\s+(.+)$').firstMatch(line);
      if (titleMatch != null) {
        pendingTitle = _unquote(titleMatch.group(1)!);
        continue;
      }
      final indexMatch = RegExp(r'^INDEX\s+\d+\s+(\d{1,2}):(\d{2}):(\d{2})')
          .firstMatch(line);
      if (indexMatch != null) {
        pendingDuration = Duration(
          minutes: int.parse(indexMatch.group(1)!),
          seconds: int.parse(indexMatch.group(2)!),
          milliseconds: int.parse(indexMatch.group(3)!) * 10,
        );
        if (currentFile != null) {
          tracks.add(PlaylistTrack(
            path: currentFile,
            title: pendingTitle,
            duration: pendingDuration,
          ));
        }
        pendingTitle = '';
        continue;
      }
      if (line.startsWith('FILE ') && currentFile == null) {
        currentFile = line.substring(5).trim();
      }
    }
    // cue 里 FILE 是整张碟，INDEX 是音轨起点；上面的逻辑已把每条 INDEX 作为一项
    return tracks;
  }

  String _writeM3u(
    List<PlaylistTrack> tracks, {
    bool extended = false,
    bool utf8Header = false,
  }) {
    final buffer = StringBuffer('#EXTM3U\n');
    for (final track in tracks) {
      if (extended && track.title.isNotEmpty) {
        buffer.writeln(
          '#EXTINF:${track.duration.inSeconds},${track.title}',
        );
      }
      buffer.writeln(track.path);
    }
    return buffer.toString();
  }

  String _writeCue(List<PlaylistTrack> tracks, String album) {
    final buffer = StringBuffer()
      ..writeln('REM GENERATED BY OmniForge')
      ..writeln('TITLE "$album"')
      ..writeln('FILE "${inputStemPlaceholder(tracks)}" WAVE');
    var offset = Duration.zero;
    for (var i = 0; i < tracks.length; i++) {
      final track = tracks[i];
      buffer.writeln('  TRACK ${(i + 1).toString().padLeft(2, '0')} AUDIO');
      if (track.title.isNotEmpty) buffer.writeln('    TITLE "${track.title}"');
      buffer.writeln('    INDEX 01 ${_cueTime(offset)}');
      offset += track.duration == Duration.zero
          ? const Duration(seconds: 1)
          : track.duration;
    }
    return buffer.toString();
  }

  String inputStemPlaceholder(List<PlaylistTrack> tracks) {
    if (tracks.isEmpty) return 'audio.wav';
    final first = tracks.first.path;
    final index = first.lastIndexOf('.');
    return index <= 0 ? '$first.wav' : '${first.substring(0, index)}.wav';
  }

  String _cueTime(Duration d) =>
      '${d.inMinutes.toString().padLeft(2, '0')}:'
      '${(d.inSeconds % 60).toString().padLeft(2, '0')}:'
      '${((d.inMilliseconds % 1000) ~/ 10).toString().padLeft(2, '0')}';

  String _unquote(String value) {
    final trimmed = value.trim();
    if (trimmed.length >= 2 &&
        trimmed.startsWith('"') &&
        trimmed.endsWith('"')) {
      return trimmed.substring(1, trimmed.length - 1);
    }
    return trimmed;
  }
}
